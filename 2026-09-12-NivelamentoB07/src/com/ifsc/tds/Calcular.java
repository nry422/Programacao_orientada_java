package com.ifsc.tds;

public class Calcular {
	
	public void tabuador(int valor) {
		
		
		
		for (int j = 1; j <= valor; j++) {
			
			System.out.println("----------------");
		
		for (int i = 1; i <= 10; i++) {
			
			
			System.out.println(j + " x " + i + " = " + (j*i));			
			
		}
		}
		
	}

}
